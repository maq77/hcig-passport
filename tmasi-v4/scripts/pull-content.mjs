// T007 (spec 009, contracts/content-contract.md): the only door words come through.
// Reads the v3 words (tmasi-next/src/content/live/en.json, the live site's own text, and the English
// labels in tmasi-next/src/content/ui.ts that were approved on v3) and writes src/content/home.en.json,
// keyed by home section. Components read nothing else; check-words.mjs checks the built page against it.
// The one addition: usa@tmasi.net from the live contact page (Mohamed's yes, 2026-10-01).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildSync } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const v3 = join(here, "..", "..", "tmasi-next", "src", "content");
const live = JSON.parse(readFileSync(join(v3, "live", "en.json"), "utf8"));

// ui.ts is TypeScript: compile it in memory and import the result.
const out = buildSync({ entryPoints: [join(v3, "ui.ts")], bundle: true, format: "esm", write: false, platform: "neutral" });
const tmp = join(here, "..", ".work", "ui.mjs");
mkdirSync(dirname(tmp), { recursive: true });
writeFileSync(tmp, out.outputFiles[0].text);
const { UI, QUOTE_THANKS } = await import(pathToFileURL(tmp).href);
const ui = UI.en;

const V3 = "/tmasi/v3";
// v3 routes [verified 2026-10-01 in src/tmasi-v3]. Menu order follows the live header.
const NAV_HREF = [`${V3}/`, `${V3}/about/`, `${V3}/services/`, `${V3}/contacts/`, `${V3}/blog/`];
const GROUP_SLUGS = ["medical-assistance", "elite-medical-concierge", "travel-assistance", "medical-tourism", "insurance-assistance"];
const POST_SLUGS = {
  "news1.php": "egypt-healthcare-authority-agreement-africa-health-excon-2025",
  "news2.php": "uniglobal-global-insurance-conference-barcelona",
  "news3.php": "itic-global-venice-2025-exhibitor",
  "news4.php": "itic-global-venice-2025-on-stage",
  "news5.php": "hansa-medica-group-partnership-grand-egyptian-museum",
  "news6.php": "itic-global-2026-istanbul-official-sponsor",
};

const h = live.home;
const s = live.shell;
const usaEmail = live.contact.offices[4].email[0];
if (usaEmail !== "usa@tmasi.net") throw new Error(`USA email changed on the contact page: ${usaEmail}`);

const home = {
  _about: "Generated by scripts/pull-content.mjs from the v3 words. Never edit by hand.",
  // The live home's own <title> and description (titles stay as they rank, spec 008 rule).
  head: live.meta.home,
  header: {
    nav: s.nav.map((label, i) => ({ label, href: NAV_HREF[i] })),
    call: s.call,
    quote: h.hero.ctaQuote,
    language: ui.language,
    languages: [
      { code: "EN", name: UI.en.langName, href: null },
      { code: "DE", name: UI.de.langName, href: `${V3}/de/` },
      { code: "PL", name: UI.pl.langName, href: `${V3}/pl/` },
      { code: "ES", name: UI.es.langName, href: `${V3}/es/` },
    ],
  },
  hero: h.hero,
  about: {
    ...h.about,
    // The v3 stats band (labels approved 2026-09-28); numbers as the site states them.
    stats: [
      { label: ui.stats[0], value: 30000, suffix: "+" },
      { label: ui.stats[1], value: 570, suffix: "+" },
      { label: ui.stats[2], text: "24/7" },
      { label: ui.stats[3], value: 5 },
    ],
  },
  relax: h.relax,
  values: h.values,
  mission: h.mission,
  why: h.why,
  services: {
    title: h.services.title,
    sub: h.services.sub,
    viewDetails: ui.viewDetails,
    groups: h.services.groups.map((g, i) => ({
      ...g,
      href: i < GROUP_SLUGS.length ? `${V3}/services/${GROUP_SLUGS[i]}/` : `${V3}/services/`,
    })),
  },
  quote: { ...s.quote, thanks: ui.thankYou, thanksText: QUOTE_THANKS.en, sending: ui.sending, errorBefore: ui.errorBefore, errorAfter: ui.errorAfter },
  hubs: {
    title: ui.hubsTitle,
    showMore: s.showMoreLocations,
    offices: s.offices.map((o) => (o.name === "USA Office" ? { ...o, email: o.email || usaEmail } : o)),
  },
  news: {
    heading: live.blog.heading,
    readMore: ui.readMore,
    viewAll: ui.viewAllNews,
    viewAllHref: `${V3}/blog/`,
    cards: live.blog.cards.slice(0, 3).map(({ image, date, title, excerpt, href }) => ({
      image, date, title, excerpt, href: `${V3}/blog/${POST_SLUGS[href]}/`,
    })),
  },
  partner: { title: ui.partnerTitle, text: ui.partnerText, getInTouch: ui.getInTouch, quote: s.quote.submit },
  footer: {
    quickLinks: ui.quickLinks,
    nav: s.footerNav.map((label, i) => ({ label, href: NAV_HREF[i] })),
    onSocial: ui.onSocial,
    copyright: ui.copyright,
    poweredBy: ui.poweredBy,
    pulse: "PULSE Marketing",
    pulseHref: "https://pulsemarketing.global/",
  },
  // Shown only in some states (menus, read-more, form results): allowed, not required on first paint.
  ui: { showMore: ui.showMore, showLess: ui.showLess, close: ui.close, openMenu: ui.openMenu, closeMenu: ui.closeMenu, messageReceived: ui.messageReceived },
};

const dest = join(here, "..", "src", "content", "home.en.json");
writeFileSync(dest, JSON.stringify(home, null, 2) + "\n");
const count = JSON.stringify(home).length;
console.log(`pull-content: wrote ${dest} (${count} chars, ${home.services.groups.length} service groups, ${home.hubs.offices.length} offices, ${home.news.cards.length} news cards)`);

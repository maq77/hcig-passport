/* Assemble the live site for healthcareig.com (go-live 2026-10-30, owner: "push website live into main website").
   Run after:  HCIG_TARGET=live node scripts/build-langs.mjs  &&  HCIG_TARGET=live npm run build
   Writes live-build/ (gitignored): English at the root, the six other languages at /de/, /pl/ ..., the lead endpoint,
   the Google Search Console file, and a .htaccess with the old site's https and www rules, one-hop 301s from every old
   address to its new page, caching and compression. Checks every page's head before it says "ready". */
import fs from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const OUT = path.resolve("out"), LANGS = path.resolve("out-langs"), DEST = path.resolve("live-build");
const index = fs.readFileSync(path.join(OUT, "index.html"), "utf8");
if (index.includes("/hcig/v6/")) { console.error("live: out/ is a preview build; run the live build first"); process.exit(1); }
fs.rmSync(DEST, { recursive: true, force: true });
fs.cpSync(OUT, DEST, { recursive: true });
for (const l of fs.readdirSync(LANGS)) {
  const src = path.join(LANGS, l);
  if (!fs.existsSync(path.join(src, "index.html"))) continue;
  if (fs.readFileSync(path.join(src, "index.html"), "utf8").includes("/hcig/v6/")) { console.error(`live: ${l} is a preview build`); process.exit(1); }
  fs.cpSync(src, path.join(DEST, l), { recursive: true });
}

/* media the pages never name stay out (as in the preview copy) */
const texts = [];
(function read(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) read(p); else if (/\.(html|txt|js|css|json|xml)$/.test(e.name) && e.name !== "manifest.json") texts.push(fs.readFileSync(p, "utf8")); } })(DEST);
let pruned = 0;
(function prune(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) prune(p); else if (!texts.some((t) => t.includes(e.name))) { fs.rmSync(p); pruned++; } } })(path.join(DEST, "media"));

/* the Google Search Console verification file of the old site stays */
fs.writeFileSync(path.join(DEST, "googled249e63cae340715.html"), "google-site-verification: googled249e63cae340715.html");

/* old addresses -> new pages, one hop each. Blog: newsN.php is post N (checked: same titles). */
const POSTS = (await import(pathToFileURL(path.resolve("src/content/blog.mjs")).href).then((m) => m.POSTS)).map((p) => [p.n, p.slug]);
const R = [
  ["^(index|index1|indexnew|indexold)\\.php$|^inde\\.html$", "/"],
  ["^(about1|aboutold)\\.php$|^about\\.html$|^about/index(old)?\\.php$", "/about/"],
  ["^group_(ceo|chairman|coo)\\.php$", "/about/leadership/"],
  ["^(services|servis)\\.php$|^services/index\\.php$", "/services/"],
  ["^partner/index\\.php$", "/partner/"],
  ["^(contact|kontakty|contactconf)\\.php$|^contacts/index\\.php$", "/contacts/"],
  ["^blog\\.php$|^blog/index\\.php$", "/blog/"],
  ...POSTS.map(([n, s]) => [`^(blog/)?news${n}\\.php$`, `/blog/${s}/`]),
  ["^de/index\\.php$", "/de/"],
  ["^de/partnerbereich(/.*)?$", "/de/partner/"],
  ["^de/(kontakt|leistungen|ueber-uns)/index\\.php$", "/de/$1/"],
];
const htaccess = `# healthcareig.com, HCIG v6 (go-live 2026-10-30). Generated by hcig-v6/scripts/build-live.mjs.
Options -Indexes
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html
AddDefaultCharset utf-8

RewriteEngine On
RewriteBase /

# www to the bare domain, http to https (kept from the old site)
RewriteCond %{HTTP_HOST} ^www\\.healthcareig\\.com [NC]
RewriteRule ^(.*)$ https://healthcareig.com/$1 [L,R=301]
RewriteCond %{HTTPS} off
RewriteRule ^(.*)$ https://%{HTTP_HOST}/$1 [L,R=301]

# the old German switch (?lang=de) and English (?lang=en)
RewriteCond %{QUERY_STRING} (^|&)lang=de(&|$) [NC]
RewriteRule ^(index\\.php)?$ /de/? [L,R=301]
RewriteCond %{QUERY_STRING} (^|&)lang=en(&|$) [NC]
RewriteRule ^(index\\.php)?$ /? [L,R=301]

# old addresses to their new pages (one hop)
${R.map(([a, b]) => `RewriteRule ${a} ${b} [L,R=301,NC]`).join("\n")}

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  <FilesMatch "\\.(js|css|woff2|webp|png|jpg|jpeg|svg|mp4|webm)$">
    Header set Cache-Control "public, max-age=31536000"
  </FilesMatch>
  <FilesMatch "\\.(html|txt|xml)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/javascript application/json image/svg+xml
</IfModule>
AddType image/webp .webp
AddType video/mp4 .mp4
AddType video/webm .webm
AddType font/woff2 .woff2
`;
fs.writeFileSync(path.join(DEST, ".htaccess"), htaccess);

/* gate: every page indexable, canonical on healthcareig.com, hreflang, og image on the live domain, no preview paths */
const bad = []; let pages = 0;
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name === "index.html") {
  const rel = path.relative(DEST, p); if (rel.split(path.sep).some((x) => x === "404" || x === "_not-found")) return; // error pages stay noindex
  pages++; const h = fs.readFileSync(p, "utf8");
  if (/noindex/i.test(h)) bad.push(`${rel}: noindex`);
  if (h.includes("/hcig/v6") || h.includes("hcig-passport")) bad.push(`${rel}: preview path`);
  if (!/<link rel="canonical" href="https:\/\/healthcareig\.com\//.test(h)) bad.push(`${rel}: canonical`);
  if (!/hreflang="x-default"/.test(h)) bad.push(`${rel}: hreflang`);
  if (!h.includes('og:image" content="https://healthcareig.com/og-hcig.jpg"')) bad.push(`${rel}: og image`);
} } })(DEST);
const robots = fs.readFileSync(path.join(DEST, "robots.txt"), "utf8");
if (!/Allow: \//.test(robots)) bad.push("robots.txt does not allow");
let n = 0, bytes = 0;
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else { n++; bytes += fs.statSync(p).size; } } })(DEST);
console.log(`live: ${pages} pages, ${n} files, ${(bytes / 1048576).toFixed(1)} MB, ${pruned} unused media left out, ${R.length} redirect rules`);
if (bad.length) { console.error("live: NOT READY\n" + bad.slice(0, 30).join("\n")); process.exit(1); }
console.log("live: ready (indexable, canonical, hreflang, og image, robots)");

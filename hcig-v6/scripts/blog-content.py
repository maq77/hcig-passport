# The 15 live blog posts, word for word, from the 2026-10-26 capture: title, dateline, paragraphs (and any sub-headings
# or lists), and each post's own photo from the site backup. Writes src/content/blog.mjs and adds post-<n> to media.json.
# Run: python scripts/blog-content.py
import html, json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
CAP = ROOT / "material/live-capture/2026-10-26"
BACKUP = ROOT / "material/backup/public_html"
IMG_OUT = ROOT / "material/media/blog"
IMG_OUT.mkdir(parents=True, exist_ok=True)

def clean(s):
    s = re.sub(r"<br\s*/?>", " ", s)
    s = re.sub(r"<[^>]+>", "", s)
    s = html.unescape(s)
    s = re.sub(r"\s+", " ", s).strip()
    return s.replace(" - ", ". ") if False else s

def fix_dashes(s):
    # house rule: no dashes. A spaced hyphen or dash joining clauses becomes a full stop or a comma (logged)
    s = re.sub(r"\s+[–—]\s+", ", ", s)
    s = re.sub(r"(?<=\w)\s+-\s+(?=[A-Z])", ". ", s)
    s = re.sub(r"\s+-\s+", ", ", s)
    s = re.sub(r"(?<=\w)[–—](?=\w)", ", ", s)
    return s

def slugify(t):
    t = t.lower().replace("&", "and").replace("’", "").replace("'", "")
    t = re.sub(r"[^a-z0-9]+", "-", t).strip("-")
    if len(t) > 80:
        t = t[:80].rsplit("-", 1)[0]
    return t

index = (CAP / "blog_.html").read_text(encoding="utf-8")
order = []
for m in re.finditer(r'href="(?:\.\./blog/|)news(\d+)\.php"', index):
    n = int(m.group(1))
    if n not in order:
        order.append(n)

# the index cards carry each post's real title and excerpt (older posts use a generic "About Us" heading)
CARD = {}
for m in re.finditer(r'<a href="news(\d+)\.php" class="news-link">\s*<img src="([^"]+)"[^>]*>\s*<strong[^>]*>(.*?)</strong>\s*<p[^>]*>(.*?)</p>', index, re.S):
    CARD[int(m.group(1))] = {"img": m.group(2), "title": fix_dashes(clean(m.group(3))), "excerpt": fix_dashes(clean(m.group(4)))}

posts = []
for n in order:
    h = (CAP / f"blog_news{n}.php.html").read_text(encoding="utf-8")
    main = h[h.find("<main"):h.find("</main>")]
    title = CARD[n]["title"] if n in CARD else clean(re.search(r"<h1[^>]*>(.*?)</h1>", main, re.S).group(1))
    img = re.search(r'<div class="new-img">\s*<img src="([^"]+)"(?: alt="([^"]*)")?', main)
    blocks = []
    for m in re.finditer(r"<(p|h2|h3|li)\b[^>]*>(.*?)</\1>", main, re.S):
        tag, inner = m.group(1), m.group(2)
        t = fix_dashes(clean(inner))
        if not t:
            continue
        blocks.append({"t": {"p": "p", "h2": "h", "h3": "h", "li": "li"}[tag], "x": t})
    TEMPLATE = {"Innovating Healthcare, Changing Lives.", "About Us", "Talk to our team", "Secure & confidential communication"}
    blocks = [x for x in blocks if x["x"] not in TEMPLATE]
    dl = re.match(r"^([^.]{2,80}?)\s*[.,]\s+(.*)$", blocks[0]["x"]) if blocks else None
    dateline = ""
    first = re.search(r"<b>(.*?)</b>", main, re.S)
    if first:
        dateline = clean(first.group(1)).rstrip(" -–—")
        for blk in blocks[:2]:
            if blk["x"].startswith(dateline):
                blk["x"] = blk["x"][len(dateline):].lstrip(" .,-–—")
                break
    key = f"post-{n}"
    if img:
        src = (BACKUP / "blog" / img.group(1)).resolve()
        if src.exists():
            dst = IMG_OUT / f"{key}{src.suffix.lower()}"
            shutil.copyfile(src, dst)
        else:
            dst = None
            print("missing image", n, img.group(1))
    posts.append({"n": n, "slug": slugify(title), "title": title, "dateline": dateline, "img": key if img else None, "alt": html.unescape(img.group(2)) if img and img.group(2) else title, "excerpt": CARD.get(n, {}).get("excerpt", ""), "blocks": blocks})

media_path = ROOT / "media.json"
media = json.loads(media_path.read_text(encoding="utf-8"))
for p in posts:
    if not p["img"]:
        continue
    f = next(IMG_OUT.glob(p["img"] + ".*"), None)
    if f:
        media[p["img"]] = {"src": str(f.relative_to(REPO)).replace("\\", "/"), "width": 1600, "note": f"blog post news{p['n']} photo (live site)"}
media_path.write_text(json.dumps(media, indent=2, ensure_ascii=False), encoding="utf-8")

out = "// The 15 live blog posts (healthcareig.com, captured 2026-10-26), word for word; generated by scripts/blog-content.py.\n"
out += "// Punctuation: spaced hyphens and dashes joining clauses became full stops or commas (house rule, logged).\n"
out += "export const POSTS = " + json.dumps(posts, indent=2, ensure_ascii=False) + ";\n"
(ROOT / "src/content/blog.mjs").write_text(out, encoding="utf-8")
for p in posts:
    print(p["n"], p["slug"], "|", p["dateline"], "|", len(p["blocks"]), "blocks", "| img" if p["img"] else "")

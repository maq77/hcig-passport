// The language layer. The English content modules (src/content/*.mjs) are the source. Each other language has one
// dictionary, i18n/<lang>.json, mapping an English string to its translation. This script:
//   node scripts/i18n-gen.mjs strings          -> i18n/strings.json (every visible English string, for translators)
//   node scripts/i18n-gen.mjs todo <lang>      -> i18n/todo-<lang>.json (strings the dictionary does not have yet)
//   node scripts/i18n-gen.mjs gen <lang>       -> .i18n/<lang>/<module>.mjs (the translated copies the build uses)
// next.config.ts points "@/content/<module>.mjs" at those copies when HCIG_LANG is set, so the pages carry only the
// words of their own language. A missing translation falls back to English and is listed, never invented.
import { mkdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const V6 = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MODULES = ["home", "pages", "maritime", "blog", "brands"];
// keys whose values are never shown as words (ids, files, links, sources, codes)
const SKIP_KEYS = new Set(["src", "slug", "img", "icon", "logo", "url", "path", "key", "short", "code", "hex", "file", "href", "id", "video", "poster", "accentFrom", "ground", "keep", "lang", "v", "countriesSrc", "factsSrc", "whatsapp", "email", "phones", "offices", "durIso", "uploaded"]);
const SKIP_EXPORTS = new Set(["LANGS", "SOCIAL_LINKS", "SITE_URL"]);
const isWord = (s) => /\p{L}/u.test(s) && !/^[a-z0-9-]+$/.test(s) && !/^(https?:|mailto:|tel:|\/|#)/.test(s);

const load = async () => {
  const mods = {};
  for (const m of MODULES) mods[m] = await import(pathToFileURL(join(V6, "src/content", `${m}.mjs`)).href);
  return mods;
};

function walk(v, fn, key = "") {
  if (typeof v === "string") return SKIP_KEYS.has(key) || !isWord(v) ? v : fn(v);
  if (Array.isArray(v)) return v.map((x) => walk(x, fn, key));
  if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x, fn, k)]));
  return v;
}

async function strings() {
  const mods = await load();
  const seen = new Set();
  for (const mod of Object.values(mods))
    for (const [name, val] of Object.entries(mod)) if (!SKIP_EXPORTS.has(name)) walk(val, (s) => (seen.add(s), s));
  return [...seen];
}

// the Gemini dictionary, then Claude's hand fixes from i18n/overrides.json on top (they always win)
const dictOf = (lang) => {
  const f = join(V6, "i18n", `${lang}.json`);
  const o = join(V6, "i18n", "overrides.json");
  const d = existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : {};
  return { ...d, ...(existsSync(o) ? JSON.parse(readFileSync(o, "utf8"))[lang] || {} : {}) };
};

const [, , cmd, lang] = process.argv;
mkdirSync(join(V6, "i18n"), { recursive: true });
if (cmd === "strings") {
  const all = await strings();
  writeFileSync(join(V6, "i18n", "strings.json"), JSON.stringify(all, null, 1));
  console.log(`strings: ${all.length}, ${all.join("").length} characters`);
} else if (cmd === "todo") {
  const d = dictOf(lang);
  const todo = (await strings()).filter((s) => !(s in d));
  writeFileSync(join(V6, "i18n", `todo-${lang}.json`), JSON.stringify(todo, null, 1));
  console.log(`${lang}: ${todo.length} to translate, ${todo.join("").length} characters`);
} else if (cmd === "gen") {
  const d = dictOf(lang);
  const mods = await load();
  const out = join(V6, ".i18n", lang);
  mkdirSync(out, { recursive: true });
  const missing = new Set();
  for (const [m, mod] of Object.entries(mods)) {
    let src = `// GENERATED by scripts/i18n-gen.mjs from src/content/${m}.mjs and i18n/${lang}.json. Do not edit.\n`;
    for (const [name, val] of Object.entries(mod)) {
      const t = SKIP_EXPORTS.has(name) ? val : walk(val, (s) => (s in d ? d[s] : (missing.add(s), s)));
      src += `export const ${name} = ${JSON.stringify(t)};\n`;
    }
    writeFileSync(join(out, `${m}.mjs`), src);
  }
  writeFileSync(join(V6, "i18n", `missing-${lang}.json`), JSON.stringify([...missing], null, 1));
  console.log(`${lang}: generated, ${missing.size} strings still in English`);
} else {
  console.log("usage: node scripts/i18n-gen.mjs strings | todo <lang> | gen <lang>");
}
